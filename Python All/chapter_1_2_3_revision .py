# | `str`     | Text data                 | Names aur text store karna             |
# | `bool`    | True / False              | Conditions ka result store karna       |
# | `list`    | Mutable collection        | Multiple values store karna            |
# | `tuple`   | Immutable collection      | Fixed values store karna               |
# | `set`     | Unique collection         | Duplicate values remove karna          |
# | `dict`    | Key-value collection      | Structured data store karna            |
# | `type()`  | Data type check karta hai | Variable ka type jaanana               |
