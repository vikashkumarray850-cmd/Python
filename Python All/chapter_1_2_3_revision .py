# Chapter 3 – Operators

# Operators ka use mathematical calculations aur comparisons karne ke liye hota hai.

# | Topic    | Kya kaam hai?                                     |
# | -------- | ------------------------------------------------- |
# | `+`      | Addition                                          |
# | `-`      | Subtraction                                       |
# | `*`      | Multiplication                                    |
# | `/`      | Division                                          |
# | `//`     | Floor Division                                    |
# | `%`      | Remainder nikalna                                 |
# | `**`     | Power calculate karna                             |
# | `==`     | Equal check karna                                 |
# | `!=`     | Not equal check karna                             |
# | `>`      | Greater than check karna                          |
# | `<`      | Less than check karna                             |
# | `>=`     | Greater than or equal                             |
# | `<=`     | Less than or equal                                |
# | `=`      | Value assign karna                                |
# | `+=`     | Existing value mein add karna                     |
# | `-=`     | Existing value mein subtract karna                |
# | `*=`     | Existing value multiply karna                     |
# | `/=`     | Existing value divide karna                       |
# | `and`    | Dono conditions True honi chahiye                 |
# | `or`     | Kam se kam ek condition True honi chahiye         |
# | `not`    | Boolean result reverse karna                      |
# | `in`     | Element present hai ya nahi check karna           |
# | `not in` | Element absent hai ya nahi check karna            |
# | `is`     | Object identity check karna                       |
# | `is not` | Object identity different hai ya nahi check karna |

