# Chapter 2 – Data Types

# Data Types batate hain ki variable mein kis tarah ka data store hai.

# | Topic     | Kya hai?                  | Kya kaam hai?                          |
# | --------- | ------------------------- | -------------------------------------- |
# | `int`     | Integer numbers           | Whole numbers store karna              |
